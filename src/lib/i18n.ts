const DICT: Record<Lang, Record<MessageKey, string>> = { en, hi };

export type T = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICT[lang] ?? en;
  return (key, vars) => {
    const one = vars && Number(String(vars.n).replace(/,/g, "")) === 1 ? (`${key}.one` as MessageKey) : null;
    let s = (one && (d[one] ?? en[one])) || d[key] || en[key] || key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function parseLang(v: string | undefined | null): Lang {
  return v === "hi" ? "hi" : "en";
}

