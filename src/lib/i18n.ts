const MONTHS_HI = ["जन॰", "फ़र॰", "मार्च", "अप्रैल", "मई", "जून", "जुल॰", "अग॰", "सित॰", "अक्टू॰", "नव॰", "दिस॰"];
const MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function formatDateL(iso: string | null | undefined, lang: Lang): string {
  if (!iso) return "—";
  const [y, m, d] = iso.slice(0, 10).split("-").map(Number);
  return `${d} ${(lang === "hi" ? MONTHS_HI : MONTHS_EN)[m - 1]} ${y}`;
}

export function timeAgoL(d: Date | string | null | undefined, lang: Lang, now = new Date()): string {
  if (!d) return lang === "hi" ? "कभी नहीं" : "never";
  const m = Math.round((now.getTime() - new Date(d).getTime()) / 60_000);
  const h = Math.round(m / 60);
  if (lang === "hi") {
    if (m < 1) return "अभी";
    if (m < 60) return `${m} मिनट पहले`;
    if (h < 48) return `${h} घंटे पहले`;
    return `${Math.round(h / 24)} दिन पहले`;
  }
  if (m < 1) return "just now";
  if (m < 60) return `${m} min ago`;
  if (h < 48) return `${h} h ago`;
  return `${Math.round(h / 24)} days ago`;
}
